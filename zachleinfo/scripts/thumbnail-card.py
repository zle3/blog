#!/usr/bin/env python3
"""Render every page's thumbnail (feature.webp) in the site's brand.

Every thumbnail on the site is generated by this script from the page's
front matter, so they all share one look (plum canvas, mauve accent, the
same type) and can be rebuilt from the repo alone. Two kinds:

Text title card (pages without a suitable image):

    thumbnailCard:
      kicker: "Self-Hosting Palworld · Part 1"
      title: ["Foundation and", "Digging In"]   # one string or a list of lines
      subtitle: "Proxmox, LinuxGSM, and the config traps"

Image card (a screenshot or diagram from the page, in a branded frame):

    thumbnailCard:
      kicker: "AI Agent Platform · Part 2"
      title: "Shipping Changes"
      image: merged-prs-daily.webp   # a file in the same folder
      focus: top                     # optional: top (default), center, bottom
      fit: cover                     # optional: cover (default) or contain

Usage (from the zachleinfo/ folder):
    python3 scripts/thumbnail-card.py              # render cards that are missing
    python3 scripts/thumbnail-card.py --all        # re-render every card
    python3 scripts/thumbnail-card.py content/about/index.md   # specific pages

Needs Pillow and PyYAML. Colours come from data/brand.yaml and fonts are
committed in scripts/fonts (DejaVu, free licence in LICENSE-DejaVu.txt), so
output is the same on any machine. Cards are 1500x1000 (3:2, the theme's
card ratio). Keep text evergreen: no job titles, numbers, or dates that
will change. See docs/brand.md and docs/images.md.
"""
import argparse
import pathlib
import sys

import yaml
from PIL import Image, ImageDraw, ImageOps

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from brandkit import CANVAS, font, rgb  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
W, H = 1500, 1000
MAX_TITLE_CHARS = 24  # per line; longer lines risk running off the card
TEXT, MUTED, ACCENT, LINE = rgb("text"), rgb("text_muted"), rgb("primary"), rgb("line")


def front_matter(path):
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        return {}
    end = text.index("---", 3)
    return yaml.safe_load(text[3:end].replace("\t", " ")) or {}


def lines_of(card):
    lines = card.get("title") or []
    lines = [lines] if isinstance(lines, str) else list(lines)
    if not lines:
        raise ValueError("thumbnailCard.title is required")
    for line in lines:
        if len(line) > MAX_TITLE_CHARS:
            print(f"  warning: title line '{line}' is {len(line)} chars; split it into two lines", file=sys.stderr)
    return lines


def centred(d, y, text, f, fill):
    d.text((W // 2, y), text, font=f, fill=fill, anchor="ma")


def render_text(card):
    lines = lines_of(card)
    im = Image.new("RGB", (W, H), CANVAS)
    d = ImageDraw.Draw(im)
    n, line_h = len(lines), 96
    top = (H - (60 + n * line_h + 90)) // 2
    centred(d, top, card.get("kicker", "zachle.info"), font(38), MUTED)
    d.rectangle((W // 2 - 45, top + 58, W // 2 + 45, top + 64), fill=ACCENT)
    for i, line in enumerate(lines):
        centred(d, top + 95 + i * line_h, line, font(84, bold=True), TEXT)
    if card.get("subtitle"):
        centred(d, top + 110 + n * line_h, card["subtitle"], font(40), MUTED)
    centred(d, H - 110, "zachle.info", font(32), ACCENT)
    return im


def fit_image(src, box_w, box_h, focus, fit):
    src = src.convert("RGB")
    if fit == "contain":
        src.thumbnail((box_w, box_h), Image.LANCZOS)
        out = Image.new("RGB", (box_w, box_h), rgb("surface"))
        out.paste(src, ((box_w - src.width) // 2, (box_h - src.height) // 2))
        return out
    y = {"top": 0.0, "center": 0.5, "bottom": 1.0}.get(focus, 0.0)
    return ImageOps.fit(src, (box_w, box_h), Image.LANCZOS, centering=(0.5, y))


def render_image(card, folder):
    lines = lines_of(card)
    im = Image.new("RGB", (W, H), CANVAS)
    d = ImageDraw.Draw(im)
    centred(d, 52, card.get("kicker", "zachle.info"), font(32), MUTED)
    d.rectangle((W // 2 - 40, 100, W // 2 + 40, 105), fill=ACCENT)
    line_h = 74
    for i, line in enumerate(lines):
        centred(d, 122 + i * line_h, line, font(62, bold=True), TEXT)
    x0, y0 = 80, 122 + len(lines) * line_h + 30
    x1, y1 = W - 80, H - 92
    shot = fit_image(Image.open(folder / card["image"]), x1 - x0, y1 - y0, card.get("focus", "top"), card.get("fit", "cover"))
    mask = Image.new("L", shot.size, 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, shot.width - 1, shot.height - 1), radius=18, fill=255)
    im.paste(shot, (x0, y0), mask)
    d.rounded_rectangle((x0 - 1, y0 - 1, x1, y1), radius=19, outline=LINE, width=2)
    centred(d, H - 66, "zachle.info", font(28), ACCENT)
    return im


def render(card, out):
    im = render_image(card, out.parent) if card.get("image") else render_text(card)
    im.save(out, "WEBP", quality=90, method=6)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("pages", nargs="*", help="index.md files to render (default: all pages with thumbnailCard)")
    ap.add_argument("--all", action="store_true", help="re-render cards even if feature.webp exists")
    args = ap.parse_args()

    pages = [pathlib.Path(p).resolve() for p in args.pages] or sorted((ROOT / "content").rglob("index.md"))
    done = 0
    for page in pages:
        card = front_matter(page).get("thumbnailCard")
        if not card:
            if args.pages:
                print(f"skip {page.relative_to(ROOT)}: no thumbnailCard in front matter", file=sys.stderr)
            continue
        out = page.parent / "feature.webp"
        if out.exists() and not (args.all or args.pages):
            continue
        render(card, out)
        print(f"rendered {out.relative_to(ROOT)}")
        done += 1
    print(f"{done} card(s) rendered")


if __name__ == "__main__":
    main()
